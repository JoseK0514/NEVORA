export const ACCESS_COPY: Record<AccessLang, AccessCopy> = { en, es };
/** The table for a language; anything but 'es' is English. */
export const accessCopy = (lang?: AccessLang | null): AccessCopy => ACCESS_COPY[lang === 'es' ? 'es' : 'en'];
/** The English messages commands.ts throws (one source, so the thrown text and the table never drift). */
export const COMMAND_MESSAGES = en.commands;
/** A message from commands.ts in the person's language; any other text (a server's own words) is returned unchanged. */
export function commandMessage(message: string, lang?: AccessLang | null): string {
  if (lang !== 'es') return message;
  const key = (Object.keys(en.commands) as (keyof AccessCopy['commands'])[]).find(name => en.commands[name] === message);
  return key ? es.commands[key] : message;
}
/** Spanish weekday, day and month ("mié, 14 oct") for a calendar date, the voice guide way. */
export const esDay = (date: string) => {
  const at = new Date(`${date}T12:00:00Z`), part = (options: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat('es-PR', { ...options, timeZone: 'UTC' }).format(at).replace('.', '');
  return `${part({ weekday: 'short' })}, ${at.getUTCDate()} ${part({ month: 'short' })}`;
};
