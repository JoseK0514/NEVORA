/** The lib's and the file reader's English error lines, said in Spanish (patterns for the ones that carry numbers). */
function spanishError(text: string) {
  const fixed: Record<string, string> = {
    "End after the start": "Pon el final después del inicio",
    "Enter a title": "Escribe un título",
    "Keep the title on one line": "Deja el título en una línea",
    "Add the text": "Añade el texto",
    "Only .txt and .md files can be loaded": "Solo se pueden cargar archivos .txt y .md",
    "File name too long": "Nombre de archivo muy largo",
    "Describe what the business does": "Describe qué hace el negocio",
    "Only .txt and .md files. Paste other text instead": "Solo archivos .txt y .md. Pega otro texto en su lugar",
    "Not UTF-8 text. Paste it instead": "No es texto UTF-8. Pégalo en su lugar",
  };
  if (fixed[text]) return fixed[text];
  let match = /^Line (\d+) has a hidden character\. Remove it$/.exec(text);
  if (match) return `La línea ${match[1]} tiene un carácter oculto. Quítalo`;
  match = /^Title too long \((\d+) of (\d+) bytes\)$/.exec(text);
  if (match) return `Título muy largo (${match[1]} de ${match[2]} bytes)`;
  match = /^Over the (.+) limit\. Split it up$/.exec(text);
  if (match) return `Supera el límite de ${match[1]}. Divídelo`;
  match = /^Over the (.+) limit\. Shorten it$/.exec(text);
  if (match) return `Supera el límite de ${match[1]}. Acórtalo`;
  return text;
}

