/** "Dec 7, 6:00 AM" in Spanish: "7 dic, 6:00 a. m." (the same parts formatBusinessDateTime composes). */
function esTimestamp(iso: string, timeZone: string) {
  const parts = new Intl.DateTimeFormat('en-US', { timeZone, month: 'numeric', day: 'numeric', hour: 'numeric', minute: '2-digit' }).formatToParts(new Date(iso));
  const value = (type: Intl.DateTimeFormatPartTypes) => parts.find(part => part.type === type)?.value ?? '';
  const months = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'];
  return `${value('day')} ${months[Number(value('month')) - 1]}, ${value('hour')}:${value('minute')} ${value('dayPeriod') === 'AM' ? 'a. m.' : 'p. m.'}`;
}

