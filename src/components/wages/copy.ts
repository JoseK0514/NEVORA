export const wagesCopy = (lang: WagesLang): WagesCopy => lang === "es" ? es : en;

/** A workplace calendar date ("2026-12-01") as "Dec 1, 2026" / "1 dic 2026". */
export function dateText(date: string, t: WagesCopy) {
  const [y, m, d] = date.split("-").map(Number);
  return new Intl.DateTimeFormat(t.locale, { timeZone: "UTC", month: "short", day: "numeric", year: "numeric" }).format(new Date(Date.UTC(y, m - 1, d)));
}
/** An instant as the workplace's calendar date. */
export function instantDate(instant: string, timeZone: string, t: WagesCopy) {
  return new Intl.DateTimeFormat(t.locale, { timeZone, month: "short", day: "numeric", year: "numeric" }).format(new Date(instant));
}
