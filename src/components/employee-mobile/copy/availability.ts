/** The zone in words, beside a deadline: "Puerto Rico time" · "hora de Puerto Rico" (English is timeZoneLabel's). */
export function zoneText(timeZone: string, english: string, lang: 'en' | 'es') {
  if (lang === 'en') return english;
  const place = timeZone.split('/').at(-1)?.replaceAll('_', ' ').trim();
  return place ? `hora de ${place}` : timeZone;
}
