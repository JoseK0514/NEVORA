export const ptoCopy = (lang: PtoLang): PtoCopy => lang === "es" ? es : en;

/** Minutes as "8 h", "7 h 30 min", "0 h"; signed when asked ("+8 h", "−4 h"). */
export function hoursText(minutes: number, signed = false) {
  const sign = minutes < 0 ? "−" : signed && minutes > 0 ? "+" : "";
  const abs = Math.abs(minutes), h = Math.floor(abs / 60), m = abs % 60;
  return `${sign}${h || !m ? `${h} h` : ""}${h && m ? " " : ""}${m ? `${m} min` : ""}`;
}
export function dateText(date: string, t: PtoCopy) {
  const [y, mo, d] = date.slice(0, 10).split("-").map(Number);
  return new Intl.DateTimeFormat(t.locale, { timeZone: "UTC", month: "short", day: "numeric", year: "numeric" }).format(new Date(Date.UTC(y, mo - 1, d)));
}
export function rangeText(start: string, end: string, t: PtoCopy) {
  return dateRange(start.slice(0, 10), end.slice(0, 10), { year: "each", locale: t.locale });
}
