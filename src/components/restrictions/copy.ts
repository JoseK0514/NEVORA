const words: Record<RestrictionsLang, RestrictionsCopy> = { en, es };
export const restrictionsCopy = (lang: RestrictionsLang): RestrictionsCopy => words[lang];

/** "8:00 AM", "10:30 p. m."; midnight (0 or 1440) is "12:00 AM" like every other time (the one time format, Nov 23,
 * 2026), so a range reads "10:00 PM – 12:00 AM". */
export function clockText(minutes: number, t: RestrictionsCopy): string {
  const hour = Math.floor(minutes / 60) % 24, rest = minutes % 60;
  return `${hour % 12 || 12}:${String(rest).padStart(2, "0")} ${hour < 12 ? t.am : t.pm}`;
}
export const spanText = (span: { start: number; end: number }, t: RestrictionsCopy) => `${clockText(span.start, t)} – ${clockText(span.end, t)}`;
/** A Monday or any calendar day: "Mon, Nov 9" (the label is a workplace date, so it is never moved by a time zone). */
export function dayText(date: string, t: RestrictionsCopy): string {
  const text = new Intl.DateTimeFormat(t.locale, { timeZone: "UTC", weekday: "short", month: "short", day: "numeric" }).format(new Date(`${date}T12:00:00Z`));
  return t.locale === "es-PR" ? text.replace(/\./g, "") : text;
}
/** The workplace's day for a moment: "Nov 12". */
export function instantText(at: string, timeZone: string, t: RestrictionsCopy): string {
  let text: string;
  try { text = new Intl.DateTimeFormat(t.locale, { timeZone, month: "short", day: "numeric" }).format(new Date(at)); }
  catch { text = new Intl.DateTimeFormat(t.locale, { timeZone: "UTC", month: "short", day: "numeric" }).format(new Date(at)); }
  return t.locale === "es-PR" ? text.replace(/\./g, "") : text;
}
