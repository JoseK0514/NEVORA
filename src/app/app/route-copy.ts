/** "Nov 30 – Dec 6" in English (the caller's dateRange), "30 nov – 6 dic" in Spanish. */
export function esDayRange(start: string, end: string) {
  const day = (iso: string) => new Intl.DateTimeFormat('es-PR', {timeZone: 'UTC', day: 'numeric', month: 'short'}).format(new Date(`${iso}T12:00:00Z`)).replace(/\./g, '');
  return `${day(start)} – ${day(end)}`;
}
