export const SCHEDULE_WORDS: Record<ScheduleLang, typeof en> = { en, es };
export type ScheduleWords = typeof en;
export const scheduleWords = (lang: ScheduleLang = "en"): ScheduleWords => SCHEDULE_WORDS[lang];

/* Dates and times (voice.md "Dates, times and numbers"). English keeps the forms the pages already drew; Spanish writes
 * "7–13 dic", "lun, 7 dic", "lunes, 7 de diciembre" and "6:00 a. m. – 2:00 p. m.". */
const locale = (lang: ScheduleLang) => lang === "es" ? "es-PR" : "en-US";
const noon = (iso: string) => new Date(`${iso}T12:00:00Z`);
const bare = (text: string, lang: ScheduleLang) => lang === "es" ? text.replace(/\./g, "") : text;
/** "Oct 19–25" / "19–25 oct": the week on screen (formatWeekRange and the compact form are the same range). */
export const weekRange = (weekStart: string, lang: ScheduleLang = "en") =>
  dateRange(weekStart, addDays(weekStart, 6), { year: "never", locale: locale(lang) });
/** "Monday, October 19" / "lunes, 19 de octubre". */
export const longDay = (date: string, lang: ScheduleLang = "en") =>
  new Intl.DateTimeFormat(locale(lang), { weekday: "long", month: "long", day: "numeric", timeZone: "UTC" }).format(noon(date));
/** "Mon, Oct 19" / "lun, 19 oct". */
export const shortDay = (date: string, lang: ScheduleLang = "en") =>
  bare(new Intl.DateTimeFormat(locale(lang), { weekday: "short", month: "short", day: "numeric", timeZone: "UTC" }).format(noon(date)), lang);
/** formatDayLabel's parts in Spanish: { weekday: "lun", day: "19 oct" }. */
export const esDayLabel = (date: string) => ({
  weekday: bare(new Intl.DateTimeFormat("es-PR", { weekday: "short", timeZone: "UTC" }).format(noon(date)), "es"),
  day: bare(new Intl.DateTimeFormat("es-PR", { month: "short", day: "numeric", timeZone: "UTC" }).format(noon(date)), "es"),
});
/** An instant in the company's zone, as the deadline rows show it. */
export const zonedDay = (iso: string, timeZone: string, lang: ScheduleLang = "en", withTime = false) =>
  bare(new Intl.DateTimeFormat(locale(lang), { timeZone, weekday: "short", month: "short", day: "numeric", ...(withTime ? { hour: "numeric", minute: "2-digit" } : {}) }).format(new Date(iso)), lang)
    .replace(/\ba m\b/g, "a. m.").replace(/\bp m\b/g, "p. m.");
/** "6:00 AM – 2:00 PM" → "6:00 a. m. – 2:00 p. m." ("All day" → "Todo el día"); English is returned as given. */
export const times = (text: string, lang: ScheduleLang = "en") =>
  lang === "es" ? (text === "All day" ? "Todo el día" : text.replace(/\bAM\b/g, "a. m.").replace(/\bPM\b/g, "p. m.")) : text;
