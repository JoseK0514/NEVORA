/** A shift's day: "Mon, Oct 5" in English, "lun, 5 oct" in Spanish (voice.md "Dates, times and numbers"). */
export function exchangeDay(date: string, lang: ExchangeLang = 'en') {
  if (lang === 'en') { const label = formatDayLabel(date); return `${label.weekday}, ${label.day}`; }
  const value = new Date(`${date}T12:00:00Z`);
  const month = new Intl.DateTimeFormat('es-PR', { month: 'short', timeZone: 'UTC' }).format(value).replace('.', '').replace(/^sept$/, 'sep');
  return `${esWeekday(date)}, ${value.getUTCDate()} ${month}`;
}
/** A clock time: "6:00 AM" in English, "6:00 a. m." in Spanish. */
export const exchangeTime = (time: string, lang: ExchangeLang = 'en') => lang === 'es' ? esTimes(formatTime(time)) : formatTime(time);
