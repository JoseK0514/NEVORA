/** The status words the English screens build from a status code ("NEEDS_REVIEW" → "Needs Review"). */
function statusLabel(status: string) {
  return status
    .toLowerCase()
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join(" ");
}
